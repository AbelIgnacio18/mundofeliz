        function cargarPagos() {
            let id = $('#ex-estudiante').val();

            if (!id) return;
            let url = "{{ route('app.mostrarcomceptospagados', ':id') }}";
            url = url.replace(':id', id);


            $.ajax({
                url: url,
                method: 'GET',
                success: function(res) {

                    $("#mesespagados").empty().show();
                    $("#mesespendientes").empty().show();
                    $("#conceptospagados").empty().show();

                    // 🔵 MESES PAGADOS
                    if (res.pagados) {
                        res.pagados.forEach(mes => {
                            $("#mesespagados").append(
                                `<span class="badge bg-secondary me-1">${mes}</span>`
                            );
                        });
                    }

                    // 🟢 MESES PENDIENTES
                    if (res.pendientes) {
                        res.pendientes.forEach(mes => {
                            $("#mesespendientes").append(
                                `<span class="badge bg-primary me-1 mes-btn" data-mes="${mes}">
                    ${mes}
                </span>`
                            );
                        });
                    }

                    // 🟣 CONCEPTOS PAGADOS 🔥
                    if (res.conceptos) {
                        res.conceptos.forEach(con => {
                            $("#conceptospagados").append(
                                `<span class="badge bg-success me-1">${con}</span>`
                            );
                        });
                    }
                }
            });
        }

